//{{{ fun: assert_vector_eq
fn assert_vector_eq(
    actual: &DVector<f64>,
    expected: &DVector<f64>,
) {
    for (actual, expected) in actual.iter().zip(expected) {
        assert_relative_eq!(*actual, expected, epsilon = 1.0e-10, max_relative = 1.0e-10);
    }
}
